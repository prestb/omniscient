<script setup>
    import { ref } from 'vue';
    import { useForm } from '@inertiajs/vue3';
    import { useToast } from '@/composables/useToast';

    const { error } = useToast();
    const showCurrentPassword = ref(false);
    const showNewPassword = ref(false);
    const showConfirmPassword = ref(false);

    // ✅ useForm — gives form.errors + form.processing automatically
    const form = useForm({
        current_password: '',
        password: '',
        password_confirmation: '',
    });

    const submit = () => {
        form.put('/password', {
            preserveScroll: true,
            onSuccess: () => {
                // ✅ No success toast — the controller flashes
                //    'Password updated successfully.'
                form.reset();
            },
            onError: (errors) => {
                // Client-side fallback. Inline errors render via form.errors.
                error('Update Failed ❌', Object.values(errors)[0] || 'Failed to update password. Please try again.', { duration: 4000 });
            },
        });
    };
</script>